import { dump } from 'js-yaml';

export interface AgentStackConfig {
  hostName: string;
  agentTrustedPubkey: string;
  agentImage: string;
  capabilities: {
    docker: boolean;
    zfs: boolean;
  };
  hlmZfsUid?: number;
  hlmZfsGid?: number;
  dockerGid?: number;
}

/** Generate a Docker Compose YAML string for the agent stack based on host capabilities. */
export function generateAgentStackCompose(config: AgentStackConfig): string {
  const { docker } = config.capabilities;
  const services: Record<string, unknown> = {};

  if (docker) {
    services['socket-proxy'] = buildSocketProxy();
  }

  services['agent'] = buildAgent(config);

  const doc: Record<string, unknown> = { services };

  if (docker) {
    doc['networks'] = {
      'agent-internal': {
        driver: 'bridge',
        internal: true,
      },
      'agent-public': {
        driver: 'bridge',
      },
    };
  }

  const header = [
    '# homelab-manager agent stack',
    '# Generated by homelab-manager UI',
    '',
  ].join('\n');

  return header + dump(doc, { lineWidth: -1, quoteStyle: 'double' });
}

/** Generate a .env file content string for the agent stack. */
export function generateAgentStackEnv(config: AgentStackConfig): string {
  const { docker, zfs } = config.capabilities;

  if (zfs) {
    if (config.hlmZfsUid === undefined || config.hlmZfsGid === undefined) {
      throw new Error('hlmZfsUid and hlmZfsGid are required when zfs capability is enabled');
    }
    if (docker && config.dockerGid === undefined) {
      throw new Error('dockerGid is required when both docker and zfs capabilities are enabled');
    }
  }

  const lines: string[] = [
    `AGENT_IMAGE=${config.agentImage}`,
    `HLM_AGENT_PORT=9090`,
    `HLM_STACKS_DIR=/opt/homelab-manager/stacks`,
  ];

  if (zfs) {
    lines.push(`HLM_ZFS_UID=${config.hlmZfsUid}`);
    lines.push(`HLM_ZFS_GID=${config.hlmZfsGid}`);
  }

  if (docker && zfs) {
    lines.push(`DOCKER_GID=${config.dockerGid}`);
  }

  return lines.join('\n') + '\n';
}

function buildSocketProxy(): Record<string, unknown> {
  return {
    image: 'lscr.io/linuxserver/socket-proxy:latest',
    container_name: 'hlm-socket-proxy',
    restart: 'unless-stopped',
    volumes: ['/var/run/docker.sock:/var/run/docker.sock:ro'],
    environment: {
      CONTAINERS: 1,
      EVENTS: 1,
      INFO: 1,
      IMAGES: 1,
      ALLOW_LOGS: 1,
      NETWORKS: 1,
      VOLUMES: 1,
      VERSION: 1,
      ALLOW_START: 1,
      ALLOW_STOP: 1,
      ALLOW_RESTARTS: 1,
      POST: 1,
      EXEC: 1,
      CONTAINERS_CREATE: 1,
      CONTAINERS_DELETE: 1,
    },
    networks: ['agent-internal'],
  };
}

const AGENT_STACKS_DIR = '/opt/homelab-manager/stacks';
// Flat, host-independent directory: the agent writes cert.pem and key.pem here
// and the manager targets the same fixed paths, so a renamed host cannot
// desync the two sides.
const TLS_DIR_NAME = 'hlm-agent-tls';

export function hostTlsDir(): string {
  return `${AGENT_STACKS_DIR}/${TLS_DIR_NAME}`;
}

export function hostTlsCertPath(): string {
  return `${hostTlsDir()}/cert.pem`;
}

export function hostTlsKeyPath(): string {
  return `${hostTlsDir()}/key.pem`;
}

function buildAgent(config: AgentStackConfig): Record<string, unknown> {
  const { docker, zfs } = config.capabilities;
  const tlsCertPath = hostTlsCertPath();
  const tlsKeyPath = hostTlsKeyPath();

  const environment: Record<string, string> = {
    AGENT_TRUSTED_PUBKEY: config.agentTrustedPubkey,
    // Must match the managed host name: manager JWTs carry it as the aud claim.
    AGENT_HOST_NAME: config.hostName,
    // The only way a ZFS-only host can report its tag: no Docker socket to inspect itself.
    AGENT_IMAGE: '${AGENT_IMAGE}',
    // Contractual: the manager restarts the agent over /containers/hlm-agent/restart.
    AGENT_CONTAINER_NAME: 'hlm-agent',
    TLS_CERT_PATH: tlsCertPath,
    TLS_KEY_PATH: tlsKeyPath,
    // Only the compose healthcheck below consumes this; without it Bun fetch rejects the self-signed cert.
    NODE_EXTRA_CA_CERTS: tlsCertPath,
  };

  if (docker) {
    environment['DOCKER_HOST'] = 'tcp://socket-proxy:2375';
  }

  const agent: Record<string, unknown> = {
    image: '${AGENT_IMAGE}',
    container_name: 'hlm-agent',
    restart: 'unless-stopped',
    ports: ['${HLM_AGENT_PORT:-9090}:9090'],
    environment,
    volumes: [] as string[],
  };

  const volumes: string[] = [
    // An agent update replaces this container, so stack files in the container's
    // writable layer would be lost.
    '${HLM_STACKS_DIR:-/opt/homelab-manager/stacks}:/opt/homelab-manager/stacks',
  ];

  if (zfs) {
    volumes.push(
      '/usr/sbin/zpool:/usr/sbin/zpool:ro',
      '/usr/sbin/zfs:/usr/sbin/zfs:ro',
      '/dev/zfs:/dev/zfs'
    );
    agent['user'] = '${HLM_ZFS_UID}:${HLM_ZFS_GID}';
  }

  agent['volumes'] = volumes;

  agent['healthcheck'] = {
    test: [
      'CMD-SHELL',
      `bun -e "fetch('https://localhost:' + (process.env.AGENT_PORT || 9090) + '/health').then(r => process.exit(r.ok ? 0 : 1)).catch(() => process.exit(1))"`,
    ],
    interval: '30s',
    timeout: '5s',
    start_period: '15s',
    retries: 3,
  };

  if (docker && zfs) {
    agent['group_add'] = ['${DOCKER_GID}'];
  }

  if (docker) {
    agent['networks'] = ['agent-internal', 'agent-public'];
    agent['depends_on'] = ['socket-proxy'];
  }

  agent['labels'] = ['hlm.managed=true', 'hlm.role=agent'];

  return agent;
}

